#!/usr/bin/env python3
"""
Compute global, per-route and ability metrics for the selected Bench2Drive-44 subset
from the real CARLA/Bench2Drive results.json structure.

Expected result JSON structure:
  {
    "_checkpoint": {
      "global_record": {...},
      "progress": [...],
      "records": [ ... per-route records ... ]
    },
    "labels": [...],
    "values": [...]
  }

Usage:
  python b2d44_metrics_from_results_json.py --json results.json --mapping bench2drive44_easiest_mapping.csv --out results_44_metrics
"""

import argparse
import csv
import json
import os
import re
from statistics import mean

NON_BLOCKING_INFRACTIONS = {"min_speed_infractions"}

ABILITY = {
    "Merging": [
        "CrossingBicycleFlow", "EnterActorFlow", "HighwayExit", "InterurbanActorFlow",
        "HighwayCutIn", "InterurbanAdvancedActorFlow", "MergerIntoSlowTrafficV2",
        "MergerIntoSlowTraffic", "NonSignalizedJunctionLeftTurn",
        "NonSignalizedJunctionRightTurn", "NonSignalizedJunctionLeftTurnEnterFlow",
        "ParkingExit", "SequentialLaneChange", "SignalizedJunctionLeftTurn",
        "SignalizedJunctionRightTurn", "SignalizedJunctionLeftTurnEnterFlow"
    ],
    "Overtaking": [
        "Accident", "AccidentTwoWays", "ConstructionObstacle", "ConstructionObstacleTwoWays",
        "HazardAtSideLaneTwoWays", "HazardAtSideLane", "ParkedObstacleTwoWays",
        "ParkedObstacle", "VehicleOpensDoorTwoWays"
    ],
    "Emergency_Brake": [
        "BlockedIntersection", "DynamicObjectCrossing", "HardBreakRoute",
        "OppositeVehicleTakingPriority", "OppositeVehicleRunningRedLight", "ParkingCutIn",
        "PedestrianCrossing", "ParkingCrossingPedestrian", "StaticCutIn",
        "VehicleTurningRoute", "VehicleTurningRoutePedestrian", "ControlLoss"
    ],
    "Give_Way": ["InvadingTurn", "YieldToEmergencyVehicle"],
    "Traffic_Signs": [
        "BlockedIntersection", "OppositeVehicleTakingPriority", "OppositeVehicleRunningRedLight",
        "PedestrianCrossing", "VehicleTurningRoute", "VehicleTurningRoutePedestrian",
        "EnterActorFlow", "CrossingBicycleFlow", "NonSignalizedJunctionLeftTurn",
        "NonSignalizedJunctionRightTurn", "NonSignalizedJunctionLeftTurnEnterFlow",
        "SignalizedJunctionLeftTurn", "SignalizedJunctionRightTurn",
        "SignalizedJunctionLeftTurnEnterFlow", "T_Junction", "VanillaNonSignalizedTurn",
        "VanillaSignalizedTurnEncounterGreenLight", "VanillaSignalizedTurnEncounterRedLight",
        "VanillaNonSignalizedTurnEncounterStopsign"
    ],
}


def safe_float(value, default=0.0):
    try:
        return float(value)
    except (TypeError, ValueError):
        return default


def load_json(path):
    with open(path, encoding="utf-8") as f:
        data = json.load(f)
    if "_checkpoint" not in data or "records" not in data["_checkpoint"]:
        raise ValueError("The JSON does not contain _checkpoint.records. Check that it is a Bench2Drive/CARLA result JSON.")
    return data


def load_mapping(path):
    mapping = {}
    with open(path, newline="", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        for row in reader:
            mapping[str(row.get("new_id", "")).strip()] = row
    return mapping


def extract_new_id(record):
    """Extract the selected-route id from RouteScenario_7_rep0 or similar."""
    route_id = str(record.get("route_id", ""))
    nums = re.findall(r"\d+", route_id)
    if nums:
        return nums[0]
    if "index" in record:
        return str(record["index"])
    return route_id


def infraction_count(record, key):
    value = record.get("infractions", {}).get(key, [])
    if isinstance(value, list):
        return len(value)
    if isinstance(value, (int, float)):
        return int(value)
    return 0


def is_success(record):
    """A strict success: route finished and no relevant infraction except min speed."""
    if record.get("status") not in ("Perfect", "Completed"):
        return False
    for key in record.get("infractions", {}):
        if key in NON_BLOCKING_INFRACTIONS:
            continue
        if infraction_count(record, key) > 0:
            return False
    return True


def score(record, name):
    return safe_float(record.get("scores", {}).get(name, 0.0))


def write_csv(path, rows, fieldnames):
    with open(path, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--json", required=True, help="Bench2Drive results.json generated by the route evaluation.")
    parser.add_argument("--mapping", required=True, help="Mapping CSV for the selected 44-route XML.")
    parser.add_argument("--out", default="results_44_metrics", help="Output folder.")
    args = parser.parse_args()

    data = load_json(args.json)
    mapping = load_mapping(args.mapping)
    records = [dict(r) for r in data["_checkpoint"]["records"]]

    for rec in records:
        rec["_new_id"] = extract_new_id(rec)
        rec["_success"] = is_success(rec)

    records.sort(key=lambda r: int(r["_new_id"]) if str(r["_new_id"]).isdigit() else 999999)
    os.makedirs(args.out, exist_ok=True)

    # Store a normalized version of the input, preserving the original global_record if present.
    normalized = {
        "_checkpoint": {
            "global_record": data.get("_checkpoint", {}).get("global_record", {}),
            "progress": data.get("_checkpoint", {}).get("progress", []),
            "records": records,
        },
        "entry_status": data.get("entry_status"),
        "eligible": data.get("eligible"),
        "labels": data.get("labels", []),
        "values": data.get("values", []),
    }
    with open(os.path.join(args.out, "normalized_results.json"), "w", encoding="utf-8") as f:
        json.dump(normalized, f, indent=2, ensure_ascii=False)

    # Per-route table.
    infraction_keys = sorted({k for r in records for k in r.get("infractions", {}).keys()})
    per_route_rows = []
    for rec in records:
        mid = str(rec["_new_id"])
        meta = mapping.get(mid, {})
        row = {
            "new_id": mid,
            "route_id": rec.get("route_id", ""),
            "ruta_original": meta.get("ruta_original", meta.get("original_route", "")),
            "original_index": meta.get("original_index", ""),
            "original_id_xml": meta.get("original_id_xml", meta.get("original_id", "")),
            "town": meta.get("town", ""),
            "scenario_type": meta.get("scenario_type", ""),
            "tipo_que_evalua": meta.get("tipo_que_evalua", ""),
            "abilities": meta.get("abilities", ""),
            "status": rec.get("status", ""),
            "success": int(rec["_success"]),
            "num_infractions": rec.get("num_infractions", ""),
            "driving_score": score(rec, "score_composed"),
            "route_completion": score(rec, "score_route"),
            "infraction_penalty": score(rec, "score_penalty"),
            "route_length": safe_float(rec.get("meta", {}).get("route_length", 0.0)),
            "duration_game": safe_float(rec.get("meta", {}).get("duration_game", 0.0)),
            "duration_system": safe_float(rec.get("meta", {}).get("duration_system", 0.0)),
        }
        for key in infraction_keys:
            row[key] = infraction_count(rec, key)
        per_route_rows.append(row)

    per_route_fields = [
        "new_id", "route_id", "ruta_original", "original_index", "original_id_xml", "town",
        "scenario_type", "tipo_que_evalua", "abilities", "status", "success", "num_infractions",
        "driving_score", "route_completion", "infraction_penalty", "route_length", "duration_game", "duration_system",
    ] + infraction_keys
    write_csv(os.path.join(args.out, "per_route_metrics_44.csv"), per_route_rows, per_route_fields)

    # Global table from records.
    if records:
        global_row = {
            "eval_num": len(records),
            "mean_driving_score": mean(score(r, "score_composed") for r in records),
            "mean_route_completion": mean(score(r, "score_route") for r in records),
            "mean_infraction_penalty": mean(score(r, "score_penalty") for r in records),
            "success_rate_percent": 100.0 * sum(r["_success"] for r in records) / len(records),
            "perfect_routes": sum(1 for r in records if r.get("status") == "Perfect"),
            "completed_routes": sum(1 for r in records if r.get("status") == "Completed"),
            "failed_routes": sum(1 for r in records if r.get("status") not in ("Perfect", "Completed")),
        }
        for key in infraction_keys:
            global_row[f"total_{key}"] = sum(infraction_count(r, key) for r in records)
    else:
        global_row = {"eval_num": 0}
    write_csv(os.path.join(args.out, "global_metrics_44.csv"), [global_row], list(global_row.keys()))

    # Also save the official label/value table included in the JSON.
    labels = data.get("labels", []) or []
    values = data.get("values", []) or []
    label_rows = [{"label": label, "value": values[i] if i < len(values) else ""} for i, label in enumerate(labels)]
    if label_rows:
        write_csv(os.path.join(args.out, "official_labels_values_from_json.csv"), label_rows, ["label", "value"])

    # Ability table.
    ability_rows = []
    for ability, scenario_list in ABILITY.items():
        selected = []
        for rec in records:
            meta = mapping.get(str(rec["_new_id"]), {})
            scenario = meta.get("scenario_type", "")
            if scenario in scenario_list:
                selected.append(rec)
        if not selected:
            continue
        ability_rows.append({
            "ability": ability,
            "num_routes_counted": len(selected),
            "mean_driving_score": mean(score(r, "score_composed") for r in selected),
            "mean_route_completion": mean(score(r, "score_route") for r in selected),
            "mean_infraction_penalty": mean(score(r, "score_penalty") for r in selected),
            "success_rate_percent": 100.0 * sum(r["_success"] for r in selected) / len(selected),
            "total_collisions_vehicle": sum(infraction_count(r, "collisions_vehicle") for r in selected),
            "total_collisions_pedestrian": sum(infraction_count(r, "collisions_pedestrian") for r in selected),
            "total_collisions_layout": sum(infraction_count(r, "collisions_layout") for r in selected),
            "total_red_light": sum(infraction_count(r, "red_light") for r in selected),
            "total_stop_infraction": sum(infraction_count(r, "stop_infraction") for r in selected),
            "total_scenario_timeouts": sum(infraction_count(r, "scenario_timeouts") for r in selected),
        })

    if ability_rows:
        ability_rows.append({
            "ability": "Mean_over_abilities",
            "num_routes_counted": "",
            "mean_driving_score": mean(r["mean_driving_score"] for r in ability_rows),
            "mean_route_completion": mean(r["mean_route_completion"] for r in ability_rows),
            "mean_infraction_penalty": mean(r["mean_infraction_penalty"] for r in ability_rows),
            "success_rate_percent": mean(r["success_rate_percent"] for r in ability_rows),
            "total_collisions_vehicle": "",
            "total_collisions_pedestrian": "",
            "total_collisions_layout": "",
            "total_red_light": "",
            "total_stop_infraction": "",
            "total_scenario_timeouts": "",
        })
    ability_fields = [
        "ability", "num_routes_counted", "mean_driving_score", "mean_route_completion",
        "mean_infraction_penalty", "success_rate_percent", "total_collisions_vehicle",
        "total_collisions_pedestrian", "total_collisions_layout", "total_red_light",
        "total_stop_infraction", "total_scenario_timeouts"
    ]
    write_csv(os.path.join(args.out, "ability_metrics_44.csv"), ability_rows, ability_fields)

    print(f"Read {len(records)} route records from {args.json}")
    print(f"Outputs saved in: {args.out}")
    print("- global_metrics_44.csv")
    print("- per_route_metrics_44.csv")
    print("- ability_metrics_44.csv")
    if label_rows:
        print("- official_labels_values_from_json.csv")
    print("- normalized_results.json")


if __name__ == "__main__":
    main()
